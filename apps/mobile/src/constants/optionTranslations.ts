import type { AppLanguage } from '../context/LanguageContext';

/**
 * Display translations for the option lists.
 *
 * The stored value stays English. Matching, filtering and everything already
 * in the database depend on it, so these translate what a member reads and
 * nothing else — pick "શાકાહારી" and the profile still records "Vegetarian".
 *
 * Not everything belongs here. Degree codes (B.E / B.Tech), currency codes
 * and country abbreviations are written in Latin script even in Gujarati and
 * Hindi text, so translating them would read worse, not better. Proper nouns
 * — nakshatras, raasis, castes, languages — are transliterated into the
 * script rather than translated, which is how they are actually written.
 */
const OPTIONS: Record<string, { hi: string; gu: string }> = {};

export function registerOptionTranslations(
  entries: Record<string, [hi: string, gu: string]>
): void {
  for (const [english, [hi, gu]] of Object.entries(entries)) {
    OPTIONS[english] = { hi, gu };
  }
}

/** The label to show for an option value, in the member's language. */
export function optionLabel(value: string, language: AppLanguage | null): string {
  if (!value) return value;
  if (!language || language === 'en-IN') return value;
  const entry = OPTIONS[value];
  if (entry) return language === 'hi-IN' ? entry.hi : entry.gu;
  // Multi-selects (hobbies, sports, music) reach the profile as one joined
  // string, so translate the parts and put them back the way they came.
  if (value.includes(',')) {
    const parts = value.split(',');
    if (parts.some((part) => OPTIONS[part.trim()])) {
      return parts.map((part) => optionLabel(part.trim(), language)).join(', ');
    }
  }
  return value;
}

